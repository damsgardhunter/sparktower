/**
 * Builds the animated header logo's assets from the source art in the repo
 * root: the bare tower (tower_logo.png) and one PNG per lightning bolt, each a
 * 1920×1080 transparent canvas.
 *
 * The bolts and the tower were drawn at different scales, so the bolts are
 * mapped onto the tower with the proportions of the finished logo
 * (client/public/favicon.png): the burst centred on the dome, at 0.47 of the
 * bolt art's size. Each image is cropped to what's visible, and its place on
 * the tower is written, as percentages of one artboard, to
 * client/src/components/animated-logo-layout.ts — with the direction each bolt
 * shoots in, from the dome's centre through the bolt's own centre.
 *
 *   node script/build-logo-assets.mjs
 *
 * To realign: change BOLT_TO_TOWER (scale and where the bolt art's burst centre
 * lands on the tower) and run it again.
 */
import { createRequire } from "module";
import { writeFileSync } from "fs";
const sharp = createRequire(import.meta.url)("sharp");

/** Bolt-art pixel → tower-art pixel. The burst centre (911, 397) lands on the dome centre (800, 457). */
const BOLT_TO_TOWER = { scale: 0.47, from: { x: 911, y: 397 }, to: { x: 800, y: 457 } };
const BOLTS = [
  ["topMid", "Top_mid_bolt.png"], ["topLeft", "Top_left_bolt.png"], ["topRight", "Top_right_bolt.png"],
  ["midLeft", "Bottom_midleft_bolt.png"], ["bottomLeft", "Bottom_left_bolt.png"],
  ["midRight", "Right_mid_bolt.png"], ["bottomRight", "bottom_right_bolt.png"],
];
const PAD = 3;
/** The artboard, in tower-art pixels: the tower and every bolt at rest, with a little air. */
const ARTBOARD = { x: 700, y: 360, w: 200, h: 310 };

async function visible(file) {
  const { data, info } = await sharp(file).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let x0 = 1e9, y0 = 1e9, x1 = -1, y1 = -1, sx = 0, sy = 0, n = 0;
  for (let y = 0; y < info.height; y++) for (let x = 0; x < info.width; x++) {
    if (data[(y * info.width + x) * 4 + 3] > 8) { x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x); y1 = Math.max(y1, y); sx += x; sy += y; n++; }
  }
  x0 = Math.max(0, x0 - PAD); y0 = Math.max(0, y0 - PAD); x1 = Math.min(info.width - 1, x1 + PAD); y1 = Math.min(info.height - 1, y1 + PAD);
  return { x0, y0, w: x1 - x0 + 1, h: y1 - y0 + 1, cx: sx / n, cy: sy / n };
}
const pct = (v) => Math.round(v * 10000) / 100;
const toTower = (x, y) => ({ x: BOLT_TO_TOWER.to.x + (x - BOLT_TO_TOWER.from.x) * BOLT_TO_TOWER.scale, y: BOLT_TO_TOWER.to.y + (y - BOLT_TO_TOWER.from.y) * BOLT_TO_TOWER.scale });
const place = (left, top, w, h) => ({ left: pct((left - ARTBOARD.x) / ARTBOARD.w), top: pct((top - ARTBOARD.y) / ARTBOARD.h), width: pct(w / ARTBOARD.w), height: pct(h / ARTBOARD.h) });

const tower = await visible("tower_logo.png");
await sharp("tower_logo.png").extract({ left: tower.x0, top: tower.y0, width: tower.w, height: tower.h }).png().toFile("client/public/brand/tower.png");
const layout = { aspect: ARTBOARD.w / ARTBOARD.h, tower: { src: "/brand/tower.png", ...place(tower.x0, tower.y0, tower.w, tower.h) }, bolts: [] };

for (const [id, file] of BOLTS) {
  const b = await visible(file);
  const src = `/brand/bolt-${id}.png`;
  await sharp(file).extract({ left: b.x0, top: b.y0, width: b.w, height: b.h }).png().toFile(`client/public${src}`);
  const tl = toTower(b.x0, b.y0);
  const dx = b.cx - BOLT_TO_TOWER.from.x, dy = b.cy - BOLT_TO_TOWER.from.y, len = Math.hypot(dx, dy);
  layout.bolts.push({ id, src, ...place(tl.x, tl.y, b.w * BOLT_TO_TOWER.scale, b.h * BOLT_TO_TOWER.scale), dirX: Math.round((dx / len) * 1000) / 1000, dirY: Math.round((dy / len) * 1000) / 1000 });
}

writeFileSync("client/src/components/animated-logo-layout.ts", `/** Generated by script/build-logo-assets.mjs — positions are percentages of the artboard; dir is the unit vector each bolt shoots along. */
export const LOGO_LAYOUT = ${JSON.stringify(layout, null, 2)} as const;
`);
